window.addEventListener("keydown", function (event) {
  if (event.defaultPrevented) {
    return;
  }

  switch (event.key) {
    case "ArrowDown":
      
      break;
    case "ArrowUp":
      
      break;
    case "ArrowLeft":
      
      break;
    case "ArrowRight":
      
      break;
    default:
      return;
  }

  event.preventDefault();
}, true);
